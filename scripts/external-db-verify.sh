#!/bin/sh
# Disposable external deployment checks. Run through `just external-db-verify`.
# Only this checkout's recorded projects and scratch directories may be removed.
set -eu
umask 077
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)
work="$root/.workspace/external-db-verify"
record="$work/created"
lock="$work/lock"
sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum; else shasum -a 256; fi; }
key=$(printf '%s' "$root" | sha256 | cut -c1-16)
fixture="sidereal-external-fixture-$key"
project="sidereal-external-app-$key"
bundled="sidereal-external-bundled-$key"
network="${fixture}_default"
port=$(expr 57000 + "$(printf '%s' "$root" | cksum | awk '{print $1}')" % 1000)
envfile="$work/app.env"
fixture_env="$work/fixture.env"
bundled_env="$work/bundled.env"
binds="$work/binds"
tls="$work/tls"
storage=/var/lib/sidereal/storage
marker=.sidereal-storage.json
held=0
started=0
pin=''

say() { echo "external-db-verify: $*"; }
fail() { echo "external-db-verify: FAILED: $*" >&2; exit 1; }

# Do not inherit operator URLs, file selections, credentials, or mount paths.
# Explicit files and env files below also prevent loading the checkout's .env.
for name in $(env | sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p'); do
    case "$name" in COMPOSE_* | POSTGRES_* | PG* | SIDEREAL_* | DATABASE_URL | STORAGE_ROOT) unset "$name" ;; esac
done
cd "$root"
case "$root" in *:* | *,* | *"'"*) fail "checkout path must not contain ':', ',' or a single quote" ;; esac

compose() {
    if [ "${selected_storage:-volume}" != volume ]; then
        set -- -f "$root/compose.storage-bind.yml" "$@"
    fi
    docker compose --project-name "$project" --project-directory "$root" --env-file "$envfile" \
        -f "$root/compose.external-db.yml" -f "$root/compose.database-tls.yml" -f "$work/app.yml" "$@"
}
fixture_compose() {
    docker compose --project-name "$fixture" --project-directory "$root" --env-file "$fixture_env" -f "$work/fixture.yml" "$@"
}
bundled_compose() {
    docker compose --project-name "$bundled" --project-directory "$root" --env-file "$bundled_env" \
        -f "$root/compose.yml" -f "$work/bundled.yml" "$@"
}
owned() {
    docker ps -a -q --filter "label=com.docker.compose.project=$1"
    docker volume ls -q --filter "label=com.docker.compose.project=$1"
    docker network ls -q --filter "label=com.docker.compose.project=$1"
}
recorded() { [ "$(cat "$record" 2>/dev/null || true)" = "$fixture $project $bundled" ]; }

# Helpers can mount only dedicated run directories, never caller-selected paths.
helper() {
    target=$1
    shift
    case "$target" in "$binds/storage" | "$binds/empty" | "$tls") ;; *) fail 'unowned helper path' ;; esac
    [ -d "$target" ] && [ ! -L "$target" ] || fail 'helper path is not a plain directory'
    entry=$1
    shift
    docker run --rm --network none --user 0:0 --cap-drop ALL --cap-add CHOWN --cap-add DAC_OVERRIDE \
        --cap-add FOWNER --security-opt no-new-privileges:true --entrypoint "$entry" \
        --mount "type=bind,source=$target,target=/target" "$pin" "$@"
}
remove_dirs() {
    for target in "$binds/storage" "$binds/empty" "$tls"; do
        [ -e "$target" ] || continue
        helper "$target" find /target -mindepth 1 -delete || return 1
        rmdir "$target" || return 1
    done
    [ ! -d "$binds" ] || rmdir "$binds"
}
remove_resources() {
    recorded || { echo 'external-db-verify: cleanup ownership record does not match' >&2; return 1; }
    # Include the named volume even when the last case selected a bind mount.
    selected_storage=volume
    # Remove network users before its fixture owner.
    compose down --volumes --remove-orphans --timeout 10 >"$work/down-app.log" 2>&1 || return 1
    bundled_compose down --volumes --remove-orphans --timeout 10 >"$work/down-bundled.log" 2>&1 || return 1
    fixture_compose down --volumes --remove-orphans --timeout 10 >"$work/down-fixture.log" 2>&1 || return 1
    for owner in "$project" "$bundled" "$fixture"; do
        [ -z "$(owned "$owner")" ] || return 1
    done
    # This tag is generated by this run, never supplied by the caller.
    docker image rm "${project}-app" >"$work/down-image.log" 2>&1 || true
    remove_dirs || return 1
    rm -f "$record" "$envfile" "$fixture_env" "$bundled_env"
}
cleanup() {
    status=$?
    trap - EXIT HUP INT TERM
    if [ "$started" = 1 ] && ! remove_resources; then
        echo "external-db-verify: cleanup failed; private diagnostics: $work" >&2
        status=1
    fi
    [ "$held" = 0 ] || rm -rf "$lock"
    exit "$status"
}
trap cleanup EXIT
trap 'exit 130' HUP INT TERM

[ ! -L "$root/.workspace" ] && [ ! -L "$work" ] || fail 'scratch root is a symbolic link'
mkdir -p "$work"
if ! mkdir "$lock" 2>/dev/null; then
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -z "$pid" ] || kill -0 "$pid" 2>/dev/null; then fail "a run already holds $lock"; fi
    mkdir "$work/reclaim" 2>/dev/null || fail 'another run is reclaiming the lock'
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -z "$pid" ] || kill -0 "$pid" 2>/dev/null; then rmdir "$work/reclaim"; fail 'the previous run is still active'; fi
    rm -rf "$lock"
    mkdir "$lock" || { rmdir "$work/reclaim"; fail 'another run acquired the lock'; }
    rmdir "$work/reclaim"
fi
held=1
echo $$ >"$lock/pid"
for tool in docker openssl curl; do command -v "$tool" >/dev/null 2>&1 || fail "$tool is required"; done
docker info >/dev/null 2>&1 || fail 'cannot reach Docker'
docker compose version >"$work/versions.log" 2>&1 || fail 'Compose 2.20 or newer is required'
docker version >>"$work/versions.log" 2>&1
pin=$(sed -n 's/^POSTGRES_IMAGE=//p' "$root/server/postgres-image.env")
[ -n "$pin" ] || fail 'PostgreSQL image pin is missing'

# Before overwriting configuration or deleting anything, establish ownership.
for owner in "$fixture" "$project" "$bundled"; do
    if [ -n "$(owned "$owner")" ] && ! recorded; then fail "project $owner has resources not recorded by this checkout; nothing removed"; fi
done
if [ -e "$binds" ] || [ -e "$tls" ]; then
    recorded || fail 'scratch data has no matching ownership record; nothing removed'
fi
write_settings() {
password=$(openssl rand -hex 32)
admin_password=$(openssl rand -hex 32)
printf 'DATABASE_URL=postgres://sidereal:%s@external-db:5432/named?sslrootcert=/etc/sidereal/postgres/ca.crt\nSIDEREAL_PORT=%s\nSIDEREAL_DATABASE_TLS_PATH=%s\n' "$password" "$port" "$tls" >"$envfile"
printf 'POSTGRES_PASSWORD=%s\n' "$admin_password" >"$fixture_env"
printf 'POSTGRES_PASSWORD=%s\nSIDEREAL_PORT=%s\n' "$password" "$((port + 1000))" >"$bundled_env"
cat >"$work/app.yml" <<EOF
services:
  app:
    networks:
      - fixture
networks:
  fixture:
    external: true
    name: $network
EOF
printf 'services:\n  app:\n    image: %s-app\n' "$project" >"$work/bundled.yml"
cat >"$work/fixture.yml" <<EOF
services:
  db:
    image: $pin
    environment:
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD:?fixture password required}
    command: [postgres, -c, ssl=on, -c, ssl_cert_file=/fixture/server.crt, -c, ssl_key_file=/fixture/server.key, -c, hba_file=/fixture/pg_hba.conf, -c, log_connections=on]
    volumes:
      - database:/var/lib/postgresql
      - type: bind
        source: $tls
        target: /fixture
        read_only: true
        bind:
          create_host_path: false
    networks:
      default:
        aliases: [external-db, wrong-host]
volumes:
  database:
EOF
}

# A killed run may have left incomplete settings. Reconstruct every file that
# Compose needs before removing recorded resources; down needs no old password.
write_settings
if recorded; then
    remove_resources || fail 'could not clean the previous recorded run'
    write_settings
fi
printf '%s\n' "$fixture $project $bundled" >"$record"

# Required-variable refusals must happen before any app container exists.
main_envfile=$envfile
envfile="$work/refusal.env"
for value in missing empty; do
    sed '/^DATABASE_URL=/d' "$main_envfile" >"$envfile"
    [ "$value" != empty ] || printf 'DATABASE_URL=\n' >>"$envfile"
    if compose config >"$work/refusal-config.log" 2>&1; then fail 'external mode accepted a missing or empty URL'; fi
    grep -Fq DATABASE_URL "$work/refusal-config.log" || fail 'missing URL refusal did not name DATABASE_URL'
    [ -z "$(docker ps -a -q --filter "label=com.docker.compose.project=$project")" ] || fail 'required-variable check created a container'
done
rm -f "$envfile"
envfile=$main_envfile

# Compare the product entries without the verification-only image and network.
entry_config() {
    POSTGRES_PASSWORD="$password" docker compose --project-name "$project" --project-directory "$root" \
        --env-file "$envfile" "$@" config
}
app_contract() {
    awk '
        /^[^ ]/ { services = ($0 == "services:") }
        services && /^  [^ ]/ { app = ($0 == "  app:") }
        app && /^    [A-Za-z_][A-Za-z0-9_-]*:/ { keep = ($1 ~ /^(build|ports|volumes|cap_drop|security_opt|restart):$/) }
        services && app && keep { print }' "$1"
}
entry_config -f "$root/compose.yml" >"$work/bundled-config.log" 2>&1
entry_config -f "$root/compose.external-db.yml" >"$work/external-config.log" 2>&1
app_contract "$work/bundled-config.log" >"$work/bundled-contract.yml"
app_contract "$work/external-config.log" >"$work/external-contract.yml"
cmp "$work/bundled-contract.yml" "$work/external-contract.yml" || fail 'bundled and external app settings differ'
sed 's/^ *//' "$work/external-contract.yml" >"$work/contract-values.yml"
for setting in 'build:' 'ports:' 'volumes:' 'cap_drop:' '- ALL' \
    'security_opt:' '- no-new-privileges:true' 'restart: unless-stopped' \
    'target: /var/lib/sidereal/storage'; do
    grep -Fxq -- "$setting" "$work/contract-values.yml" || fail "app configuration lost $setting"
done
if SIDEREAL_DATABASE_PATH="$binds/database" entry_config -f "$root/compose.external-db.yml" \
    -f "$root/compose.database-bind.yml" >"$work/database-bind-refusal.log" 2>&1; then
    fail 'external mode accepted the bundled database bind override'
fi
grep -Fq 'neither an image nor a build' "$work/database-bind-refusal.log" || fail 'unexpected database bind override refusal'
# Resolved URLs stay private and are unnecessary once these checks pass.
rm -f "$work/bundled-config.log" "$work/external-config.log"

if [ "${1:-}" = --config-only ]; then
    [ "$(compose config --services)" = app ] || fail 'external configuration includes another service'
    [ "$(compose config --volumes)" = storage ] || fail 'external configuration includes database storage'
    # Capture privately, then check that only generated values reached the app.
    compose config >"$work/config.log" 2>&1
    grep -Fq "postgres://sidereal:$password@external-db:" "$work/config.log" || fail 'generated URL was overridden'
    grep -Fq "source: $tls" "$work/config.log" || fail 'generated certificate path was overridden'
    rm -f "$record" "$envfile" "$fixture_env" "$bundled_env" "$work/config.log"
    say 'isolated configuration passed; no resources created'
    exit 0
fi

started=1
mkdir -p "$tls" "$binds/storage" "$binds/empty"
chmod 755 "$tls" "$binds" "$binds/storage" "$binds/empty"
say 'generating disposable fixture certificates'
openssl req -x509 -newkey rsa:2048 -nodes -keyout "$tls/ca.key" -out "$tls/ca.crt" -days 2 -subj '/CN=Sidereal external fixture CA' >"$work/certificates.log" 2>&1
openssl req -newkey rsa:2048 -nodes -keyout "$tls/server.key" -out "$tls/server.csr" -subj '/CN=external-db' >>"$work/certificates.log" 2>&1
printf 'subjectAltName=DNS:external-db\nextendedKeyUsage=serverAuth\n' >"$tls/server.ext"
openssl x509 -req -in "$tls/server.csr" -CA "$tls/ca.crt" -CAkey "$tls/ca.key" -set_serial 1 -out "$tls/server.crt" -days 2 -extfile "$tls/server.ext" >>"$work/certificates.log" 2>&1
openssl req -x509 -newkey rsa:2048 -nodes -keyout "$tls/wrong-ca.key" -out "$tls/wrong-ca.crt" -days 2 -subj '/CN=Wrong external fixture CA' >>"$work/certificates.log" 2>&1
rm -f "$tls/ca.key" "$tls/wrong-ca.key" "$tls/server.csr" "$tls/server.ext"
chmod 644 "$tls"/*.crt
chmod 600 "$tls/server.key"
helper "$tls" chown postgres:postgres /target/server.key >"$work/permissions.log" 2>&1
helper "$binds/storage" chown 10001:10001 /target >>"$work/permissions.log" 2>&1
helper "$binds/empty" chown 10001:10001 /target >>"$work/permissions.log" 2>&1

hba() {
    printf 'local all all trust\n' >"$tls/pg_hba.conf"
    if [ "$1" = tls-only ]; then printf 'hostnossl all sidereal all reject\n' >>"$tls/pg_hba.conf"; fi
    printf 'host all all all scram-sha-256\n' >>"$tls/pg_hba.conf"
    chmod 644 "$tls/pg_hba.conf"
}
hba tls-only
sql() { fixture_compose exec -T db psql -X -U postgres -d "${database:-postgres}" -v ON_ERROR_STOP=1 -Atc "$1"; }
fixture_identity() {
    docker inspect --format '{{.Id}} {{.State.StartedAt}}' "$(fixture_compose ps -q db)"
}
wait_database() {
    waited=0
    until fixture_compose exec -T db pg_isready -q -h 127.0.0.1; do
        [ "$waited" -lt 180 ] || fail 'fixture did not accept connections within 180 seconds'
        sleep 1
        waited=$((waited + 1))
    done
}
say 'starting the separate PostgreSQL fixture'
fixture_compose up -d >"$work/fixture-up.log" 2>&1 || fail "fixture startup failed; see $work/fixture-up.log"
wait_database >"$work/fixture-ready.log" 2>&1
sql "CREATE ROLE sidereal LOGIN NOSUPERUSER NOCREATEDB PASSWORD '$password'" >"$work/provision.log" 2>&1
for database_name in named binds isolated unrelated newer; do
    sql "CREATE DATABASE $database_name OWNER sidereal" >>"$work/provision.log" 2>&1
done
[ "$(sql "SELECT rolsuper OR rolcreatedb FROM pg_roles WHERE rolname='sidereal'")" = f ] || fail 'app login has administrator privileges'
fixture_before=$(fixture_identity)
compose down --volumes --timeout 10 >"$work/app-only-down.log" 2>&1
[ "$(fixture_identity)" = "$fixture_before" ] || fail 'app cleanup changed the external service'
docker network inspect "$network" >"$work/network.log" 2>&1 || fail 'app cleanup removed fixture network'
if [ "${1:-}" = --fixture-only ]; then
    say 'fixture TLS setup and app-only cleanup passed'
    exit 0
fi

# Select only generated fixture URLs and this run's managed-storage directories.
app_settings() {
    database=$1
    selected_storage=${2:-volume}
    query=${3:-sslrootcert=/etc/sidereal/postgres/ca.crt}
    host=${4:-external-db}
    printf 'DATABASE_URL=postgres://sidereal:%s@%s:5432/%s?%s\nSIDEREAL_PORT=%s\nSIDEREAL_DATABASE_TLS_PATH=%s\n' \
        "$password" "$host" "$database" "$query" "$port" "$tls" >"$envfile"
    cat >"$work/app.yml" <<EOF
services:
  app:
    networks: [fixture]
networks:
  fixture:
    external: true
    name: $network
EOF
    case "$selected_storage" in
        volume) ;;
        "$binds/storage" | "$binds/empty")
            # Include the product storage override, not a duplicate test mount.
            printf 'SIDEREAL_STORAGE_PATH=%s\n' "$selected_storage" >>"$envfile"
            ;;
        *) fail 'unowned app storage selection' ;;
    esac
}

code() { curl -s --max-time 3 -o "$work/http-body" -w '%{http_code}' "http://127.0.0.1:$port$1" || true; }
wait_ready() {
    waited=0
    until [ "$(code /readyz)" = 200 ]; do
        [ "$waited" -lt 180 ] || fail "app did not reach readiness; private diagnostics: $work"
        sleep 1
        waited=$((waited + 1))
    done
    [ "$(cat "$work/http-body")" = '{"status":"ready"}' ] || fail 'unexpected readiness body'
}
start_app() {
    compose up -d --no-build >"$work/app-up.log" 2>&1 || fail "app creation failed; see $work/app-up.log"
    wait_ready
}
app_logs() { compose logs --no-color --no-log-prefix app; }
no_secret() {
    app_logs >"$work/app.log" 2>&1
    for secret in "$password" "$admin_password" 'postgres://' 'postgresql://'; do
        if grep -Fq "$secret" "$work/app.log"; then fail 'app log exposed credentials or a connection URL'; fi
    done
}
records() {
    sql "SELECT coalesce(jsonb_agg(to_jsonb(m) ORDER BY version), '[]') FROM _sqlx_migrations m"
    sql 'SELECT row_to_json(m) FROM sidereal_metadata m'
}
retained() {
    records
    compose exec -T app cat "$storage/$marker"
    compose exec -T app cat "$storage/sentinel"
}
certificate_mount() {
    [ "$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "/etc/sidereal/postgres"}}{{.Source}} {{.RW}}{{end}}{{end}}' "$(compose ps -q app)")" = "$tls false" ] \
        || fail 'certificate mount is not the generated read-only directory'
}
recreate() {
    retained >"$work/retained-before"
    fixture_before=$(fixture_identity)
    compose down --timeout 10 >"$work/recreate.log" 2>&1
    [ "$(fixture_identity)" = "$fixture_before" ] || fail 'app removal changed external container identity'
    docker network inspect "$network" >/dev/null || fail 'app removal deleted fixture network'
    start_app
    retained >"$work/retained-after"
    cmp "$work/retained-before" "$work/retained-after" || fail 'app recreation changed retained state'
    [ "$(fixture_identity)" = "$fixture_before" ] || fail 'app recreation restarted external database'
    no_secret
}

say 'building the packaged app image'
compose build >"$work/build.log" 2>&1 || fail "app build failed; see $work/build.log"
for mode in named binds; do
    say "checking initialization and recreation ($mode storage)"
    if [ "$mode" = binds ]; then app_settings binds "$binds/storage"; else app_settings named; fi
    start_app
    certificate_mount
    [ "$(compose exec -T app id -u):$(compose exec -T app id -g)" = 10001:10001 ] || fail 'app identity changed'
    [ "$(sql 'SELECT count(*) FROM _sqlx_migrations WHERE success')" = 2 ] || fail 'expected two successful migrations'
    [ "$(compose exec -T app ls -A "$storage")" = "$marker" ] || fail 'first start left unexpected storage files'
    pairing=$(sql 'SELECT storage_id FROM sidereal_metadata')
    compose exec -T app cat "$storage/$marker" | grep -Fq "\"storage_id\":\"$pairing\"" || fail 'marker does not match pairing'
    mounted=$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "/var/lib/sidereal/storage"}}{{.Type}} {{if eq .Type "volume"}}{{.Name}}{{else}}{{.Source}}{{end}}{{end}}{{end}}' "$(compose ps -q app)")
    if [ "$mode" = binds ]; then expected="bind $binds/storage"; else expected="volume ${project}_storage"; fi
    [ "$mounted" = "$expected" ] || fail 'unexpected managed-storage mount'
    compose exec -T app sh -c 'printf "retained external sentinel\n" > "$STORAGE_ROOT/sentinel"'
    recreate
    compose down --timeout 10 >"$work/app-between.log" 2>&1
done
if [ "${1:-}" = --retention-only ]; then
    say 'named-volume and bind-storage retention passed'
    exit 0
fi

expect_failure() {
    diagnostic=$1
    compose up -d --no-build --force-recreate >"$work/refusal-up.log" 2>&1 || fail 'could not create refusal-case app'
    waited=0
    until app_logs 2>/dev/null | grep -Fq "$diagnostic"; do
        [ "$waited" -lt 180 ] || fail "missing expected diagnostic: $diagnostic"
        sleep 1
        waited=$((waited + 1))
    done
    [ "$(code /healthz)" = 000 ] || fail 'refused startup bound HTTP'
    app_logs | grep -Fq 'sidereal-server listening' && fail 'refused startup briefly bound HTTP'
    no_secret
    compose stop --timeout 10 >"$work/refusal-stop.log" 2>&1
}
bundled_retained() {
    bundled_compose exec -T db psql -X -U sidereal -d sidereal -Atc 'SELECT row_to_json(m) FROM sidereal_metadata m'
    bundled_compose exec -T app cat "$storage/$marker"
}

say 'checking fresh external storage against an existing bundled installation'
# Finish the earlier disposable named-volume case before the fresh-install case.
app_settings isolated
compose down --volumes --timeout 10 >"$work/named-finished.log" 2>&1
bundled_compose up -d --no-build --wait --wait-timeout 180 >"$work/bundled-up.log" 2>&1 || fail 'bundled baseline failed to start'
bundled_retained >"$work/bundled-before"
bundled_pairing=$(bundled_compose exec -T db psql -X -U sidereal -d sidereal -Atc 'SELECT storage_id FROM sidereal_metadata')
start_app
external_pairing=$(sql 'SELECT storage_id FROM sidereal_metadata')
[ "$external_pairing" != "$bundled_pairing" ] || fail 'fresh external database adopted bundled storage'
external_volume=$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "/var/lib/sidereal/storage"}}{{.Name}}{{end}}{{end}}' "$(compose ps -q app)")
bundled_volume=$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "/var/lib/sidereal/storage"}}{{.Name}}{{end}}{{end}}' "$(bundled_compose ps -q app)")
[ -n "$external_volume" ] && [ "$external_volume" != "$bundled_volume" ] || fail 'installations share a storage volume'
bundled_retained >"$work/bundled-after"
cmp "$work/bundled-before" "$work/bundled-after" || fail 'fresh external installation changed bundled storage or pairing'
compose down --timeout 10 >"$work/isolated-down.log" 2>&1
bundled_compose stop >"$work/bundled-stop.log" 2>&1

say 'checking refusal of empty substitute storage for a paired database'
app_settings binds "$binds/empty"
records >"$work/missing-marker-before"
expect_failure 'storage marker is missing'
records >"$work/missing-marker-after"
cmp "$work/missing-marker-before" "$work/missing-marker-after" || fail 'missing marker changed paired database'
helper "$binds/empty" sh -c 'test -z "$(ls -A /target)"' || fail 'missing-marker refusal wrote to empty substitute'
app_settings binds "$binds/storage"
start_app
if [ "${1:-}" = --storage-only ]; then
    say 'fresh storage isolation and missing-marker refusal passed'
    exit 0
fi

say 'proving default remote TLS against a plaintext-rejecting fixture'
retained >"$work/tls-before"
app_settings binds "$binds/storage" sslmode=disable
expect_failure 'database login rejected'
app_settings binds "$binds/storage"
if grep -q sslmode "$envfile"; then fail 'default TLS proof supplied an explicit sslmode'; fi
start_app
retained >"$work/tls-after"
cmp "$work/tls-before" "$work/tls-after" || fail 'TLS control changed retained state'
if [ "${1:-}" = --tls-only ]; then
    say 'default remote TLS and failing plaintext control passed'
    exit 0
fi

dump_database() {
    # PostgreSQL randomizes the psql restriction token on each dump.
    fixture_compose exec -T db pg_dump -U postgres -d "$database" --no-owner --no-privileges \
        >"$work/dump-raw.sql" || fail 'could not snapshot database contents'
    sed '/^\\restrict /d; /^\\unrestrict /d' "$work/dump-raw.sql"
}
say 'checking CA and hostname rejection with plaintext available'
hba allow-plaintext
sql 'SELECT pg_reload_conf()' >"$work/hba-reload.log"
# A successful plaintext control proves fallback would succeed here.
app_settings binds "$binds/storage" sslmode=disable
start_app
dump_database >"$work/rejection-before.sql"
compose down --timeout 10 >"$work/rejection-down.log" 2>&1
for rejection in untrusted wrong-host; do
    case "$rejection" in
        untrusted) app_settings binds "$binds/storage" sslrootcert=/etc/sidereal/postgres/wrong-ca.crt ;;
        wrong-host) app_settings binds "$binds/storage" sslrootcert=/etc/sidereal/postgres/ca.crt wrong-host ;;
    esac
    expect_failure 'database TLS verification failed'
    dump_database >"$work/rejection-after.sql"
    cmp "$work/rejection-before.sql" "$work/rejection-after.sql" || fail 'TLS refusal changed database contents'
done
app_settings binds "$binds/storage"
start_app
if [ "${1:-}" = --rejection-only ]; then
    say 'untrusted CA and wrong hostname refused without plaintext fallback'
    exit 0
fi

authorization_count() {
    fixture_compose logs --no-color db >"$work/authorizations.log" 2>&1
    grep -c 'connection authorized: user=sidereal ' "$work/authorizations.log" || true
}
say 'checking certificate-file refusal before authenticated connections'
dump_database >"$work/cert-file-before.sql"
compose down --timeout 10 >"$work/cert-file-down.log" 2>&1
say 'checking a missing certificate source directory'
sed "s|^SIDEREAL_DATABASE_TLS_PATH=.*|SIDEREAL_DATABASE_TLS_PATH=$work/absent-certificates|" "$envfile" >"$work/absent.env"
mv "$work/absent.env" "$envfile"
if compose up -d --no-build >"$work/absent-certificates.log" 2>&1; then fail 'Compose accepted a missing certificate directory'; fi
grep -Fq 'bind source path does not exist' "$work/absent-certificates.log" || fail 'certificate source refusal has an unexpected diagnostic'
[ ! -e "$work/absent-certificates" ] || fail 'Compose created the missing certificate directory'
[ -z "$(compose ps -a -q app)" ] || fail 'Compose created an app container with a missing certificate directory'
app_settings binds "$binds/storage"
printf 'distinctive unreadable certificate contents\n' >"$tls/unreadable.crt"
chmod 000 "$tls/unreadable.crt"
authorized=$(authorization_count)
[ "$authorized" -gt 0 ] || fail 'fixture authorization logging did not observe earlier app connections'
for certificate in distinctive-missing.crt unreadable.crt; do
    app_settings binds "$binds/storage" "sslrootcert=/etc/sidereal/postgres/$certificate"
    expect_failure 'database TLS certificate file unreadable'
    [ "$(authorization_count)" = "$authorized" ] || fail 'certificate-file refusal authenticated to PostgreSQL'
    for private in "$certificate" /etc/sidereal/postgres 'distinctive unreadable certificate contents'; do
        if grep -Fq "$private" "$work/app.log"; then fail 'certificate diagnostic exposed a path or file content'; fi
    done
    dump_database >"$work/cert-file-after.sql"
    cmp "$work/cert-file-before.sql" "$work/cert-file-after.sql" || fail 'certificate-file refusal changed database contents'
done

say 'checking refusal of unrelated data and incompatible history'
