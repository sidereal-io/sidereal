#!/bin/sh
# Disposable external deployment checks. Run through `just external-db-verify`.
# Only this checkout's recorded projects and scratch directories may be removed.
set -eu
umask 077
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)
work="$root/.workspace/external-db-verify"
record="$work/created"
lock="$work/lock"
sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum; else shasum -a 256; fi; }
key=$(printf '%s' "$root" | sha256 | cut -c1-16)
fixture="sidereal-external-fixture-$key"
project="sidereal-external-app-$key"
bundled="sidereal-external-bundled-$key"
network="${fixture}_default"
port=$(expr 57000 + "$(printf '%s' "$root" | cksum | awk '{print $1}')" % 1000)
envfile="$work/app.env"
fixture_env="$work/fixture.env"
bundled_env="$work/bundled.env"
binds="$work/binds"
tls="$work/tls"
storage=/var/lib/sidereal/storage
marker=.sidereal-storage.json
held=0
started=0
pin=''

say() { echo "external-db-verify: $*"; }
fail() { echo "external-db-verify: FAILED: $*" >&2; exit 1; }

# Do not inherit operator URLs, file selections, credentials, or mount paths.
# Explicit files and env files below also prevent loading the checkout's .env.
for name in $(env | sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p'); do
    case "$name" in COMPOSE_* | POSTGRES_* | PG* | SIDEREAL_* | DATABASE_URL | STORAGE_ROOT) unset "$name" ;; esac
done
cd "$root"
case "$root" in *:* | *,* | *"'"*) fail "checkout path must not contain ':', ',' or a single quote" ;; esac

compose() {
    docker compose --project-name "$project" --project-directory "$root" --env-file "$envfile" \
        -f "$root/compose.external-db.yml" -f "$root/compose.database-tls.yml" -f "$work/app.yml" "$@"
}
fixture_compose() {
    docker compose --project-name "$fixture" --project-directory "$root" --env-file "$fixture_env" -f "$work/fixture.yml" "$@"
}
bundled_compose() {
    docker compose --project-name "$bundled" --project-directory "$root" --env-file "$bundled_env" \
        -f "$root/compose.yml" -f "$work/bundled.yml" "$@"
}
owned() {
    docker ps -a -q --filter "label=com.docker.compose.project=$1"
    docker volume ls -q --filter "label=com.docker.compose.project=$1"
    docker network ls -q --filter "label=com.docker.compose.project=$1"
}
recorded() { [ "$(cat "$record" 2>/dev/null || true)" = "$fixture $project $bundled" ]; }

# Helpers can mount only dedicated run directories, never caller-selected paths.
helper() {
    target=$1
    shift
    case "$target" in "$binds/storage" | "$binds/empty" | "$tls") ;; *) fail 'unowned helper path' ;; esac
    [ -d "$target" ] && [ ! -L "$target" ] || fail 'helper path is not a plain directory'
    entry=$1
    shift
    docker run --rm --network none --user 0:0 --cap-drop ALL --cap-add CHOWN --cap-add DAC_OVERRIDE \
        --cap-add FOWNER --security-opt no-new-privileges:true --entrypoint "$entry" \
        --mount "type=bind,source=$target,target=/target" "$pin" "$@"
}
remove_dirs() {
    for target in "$binds/storage" "$binds/empty" "$tls"; do
        [ -e "$target" ] || continue
        helper "$target" find /target -mindepth 1 -delete || return 1
        rmdir "$target" || return 1
    done
    [ ! -d "$binds" ] || rmdir "$binds"
}
remove_resources() {
    recorded || { echo 'external-db-verify: cleanup ownership record does not match' >&2; return 1; }
    # Remove network users before its fixture owner.
    compose down --volumes --remove-orphans --timeout 10 >"$work/down-app.log" 2>&1 || return 1
    bundled_compose down --volumes --remove-orphans --timeout 10 >"$work/down-bundled.log" 2>&1 || return 1
    fixture_compose down --volumes --remove-orphans --timeout 10 >"$work/down-fixture.log" 2>&1 || return 1
    for owner in "$project" "$bundled" "$fixture"; do
        [ -z "$(owned "$owner")" ] || return 1
    done
    # This tag is generated by this run, never supplied by the caller.
    docker image rm "${project}-app" >"$work/down-image.log" 2>&1 || true
    remove_dirs || return 1
    rm -f "$record" "$envfile" "$fixture_env" "$bundled_env"
}
cleanup() {
    status=$?
    trap - EXIT HUP INT TERM
    if [ "$started" = 1 ] && ! remove_resources; then
        echo "external-db-verify: cleanup failed; private diagnostics: $work" >&2
        status=1
    fi
    [ "$held" = 0 ] || rm -rf "$lock"
    exit "$status"
}
trap cleanup EXIT
trap 'exit 130' HUP INT TERM

[ ! -L "$root/.workspace" ] && [ ! -L "$work" ] || fail 'scratch root is a symbolic link'
mkdir -p "$work"
if ! mkdir "$lock" 2>/dev/null; then
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -z "$pid" ] || kill -0 "$pid" 2>/dev/null; then fail "a run already holds $lock"; fi
    mkdir "$work/reclaim" 2>/dev/null || fail 'another run is reclaiming the lock'
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -z "$pid" ] || kill -0 "$pid" 2>/dev/null; then rmdir "$work/reclaim"; fail 'the previous run is still active'; fi
    rm -rf "$lock"
    mkdir "$lock" || { rmdir "$work/reclaim"; fail 'another run acquired the lock'; }
    rmdir "$work/reclaim"
fi
held=1
echo $$ >"$lock/pid"
for tool in docker openssl curl; do command -v "$tool" >/dev/null 2>&1 || fail "$tool is required"; done
docker info >/dev/null 2>&1 || fail 'cannot reach Docker'
docker compose version >"$work/versions.log" 2>&1 || fail 'Compose 2.20 or newer is required'
docker version >>"$work/versions.log" 2>&1
pin=$(sed -n 's/^POSTGRES_IMAGE=//p' "$root/server/postgres-image.env")
[ -n "$pin" ] || fail 'PostgreSQL image pin is missing'

# Before overwriting configuration or deleting anything, establish ownership.
for owner in "$fixture" "$project" "$bundled"; do
    if [ -n "$(owned "$owner")" ] && ! recorded; then fail "project $owner has resources not recorded by this checkout; nothing removed"; fi
done
if [ -e "$binds" ] || [ -e "$tls" ]; then
    recorded || fail 'scratch data has no matching ownership record; nothing removed'
fi
if recorded; then remove_resources || fail 'could not clean the previous recorded run'; fi
printf '%s\n' "$fixture $project $bundled" >"$record"

password=$(openssl rand -hex 32)
admin_password=$(openssl rand -hex 32)
printf 'DATABASE_URL=postgres://sidereal:%s@external-db:5432/named?sslrootcert=/etc/sidereal/postgres/ca.crt\nSIDEREAL_PORT=%s\nSIDEREAL_DATABASE_TLS_PATH=%s\n' "$password" "$port" "$tls" >"$envfile"
printf 'POSTGRES_PASSWORD=%s\n' "$admin_password" >"$fixture_env"
printf 'POSTGRES_PASSWORD=%s\nSIDEREAL_PORT=%s\n' "$password" "$((port + 1000))" >"$bundled_env"
cat >"$work/app.yml" <<EOF
services:
  app:
    networks:
      - fixture
networks:
  fixture:
    external: true
    name: $network
EOF
printf 'services:\n  app:\n    image: %s-app\n' "$project" >"$work/bundled.yml"
# Fixture configuration is added before any resources are created.

if [ "${1:-}" = --config-only ]; then
    [ "$(compose config --services)" = app ] || fail 'external configuration includes another service'
    [ "$(compose config --volumes)" = storage ] || fail 'external configuration includes database storage'
    # Capture privately, then check that only generated values reached the app.
    compose config >"$work/config.log" 2>&1
    grep -Fq "postgres://sidereal:$password@external-db:" "$work/config.log" || fail 'generated URL was overridden'
    grep -Fq "source: $tls" "$work/config.log" || fail 'generated certificate path was overridden'
    rm -f "$record" "$envfile" "$fixture_env" "$bundled_env" "$work/config.log"
    say 'isolated configuration passed; no resources created'
    exit 0
fi

say 'project ownership and isolated settings prepared'
