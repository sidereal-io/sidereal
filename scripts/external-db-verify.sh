#!/bin/sh
# Disposable external deployment checks. Run through `just external-db-verify`.
# Only this checkout's recorded projects and scratch directories may be removed.
set -eu
[ "$#" = 0 ] || { echo "usage: just external-db-verify (config checks: just check-compose)" >&2; exit 2; }
umask 077
root=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd -P)
work="$root/.workspace/external-db-verify"
record="$work/created"
lock="$work/lock"
sha256() { if command -v sha256sum >/dev/null 2>&1; then sha256sum; else shasum -a 256; fi; }
key=$(printf '%s' "$root" | sha256 | cut -c1-16)
fixture="sidereal-external-fixture-$key"
project="sidereal-external-app-$key"
network="${fixture}_default"
port=$(expr 57000 + "$(printf '%s' "$root" | cksum | awk '{print $1}')" % 1000)
envfile="$work/app.env"
fixture_env="$work/fixture.env"
tls="$work/tls"
storage=/var/lib/sidereal/storage
marker=.sidereal-storage.json
held=0
started=0
pin=''

say() { echo "external-db-verify: $*"; }
fail() { echo "external-db-verify: FAILED: $*" >&2; exit 1; }

# Do not inherit operator URLs, file selections, credentials, or mount paths.
# Explicit files and env files below also prevent loading the checkout's .env.
for name in $(env | sed -n 's/^\([A-Za-z_][A-Za-z0-9_]*\)=.*/\1/p'); do
    case "$name" in COMPOSE_* | POSTGRES_* | PG* | SIDEREAL_* | DATABASE_URL | STORAGE_ROOT) unset "$name" ;; esac
done
cd "$root"
case "$root" in *:* | *,* | *"'"*) fail "checkout path must not contain ':', ',' or a single quote" ;; esac

compose() {
    docker compose --project-name "$project" --project-directory "$root" --env-file "$envfile" \
        -f "$root/compose.external-db.yml" -f "$root/compose.database-tls.yml" -f "$work/app.yml" "$@"
}
fixture_compose() {
    docker compose --project-name "$fixture" --project-directory "$root" --env-file "$fixture_env" -f "$work/fixture.yml" "$@"
}
owned() {
    docker ps -a -q --filter "label=com.docker.compose.project=$1"
    docker volume ls -q --filter "label=com.docker.compose.project=$1"
    docker network ls -q --filter "label=com.docker.compose.project=$1"
}
recorded() { [ "$(cat "$record" 2>/dev/null || true)" = "$fixture $project" ]; }

# Helpers can mount only dedicated run directories, never caller-selected paths.
helper() {
    target=$1
    shift
    case "$target" in "$tls") ;; *) fail 'unowned helper path' ;; esac
    [ -d "$target" ] && [ ! -L "$target" ] || fail 'helper path is not a plain directory'
    entry=$1
    shift
    docker run --rm --network none --user 0:0 --cap-drop ALL --cap-add CHOWN --cap-add DAC_OVERRIDE \
        --cap-add FOWNER --security-opt no-new-privileges:true --entrypoint "$entry" \
        --mount "type=bind,source=$target,target=/target" "$pin" "$@"
}
remove_dirs() {
    for target in "$tls"; do
        [ -e "$target" ] || continue
        helper "$target" find /target -mindepth 1 -delete || return 1
        rmdir "$target" || return 1
    done
}
remove_resources() {
    recorded || { echo 'external-db-verify: cleanup ownership record does not match' >&2; return 1; }
    # Remove network users before its fixture owner.
    compose down --volumes --remove-orphans --timeout 10 >"$work/down-app.log" 2>&1 || return 1
    fixture_compose down --volumes --remove-orphans --timeout 10 >"$work/down-fixture.log" 2>&1 || return 1
    for owner in "$project" "$fixture"; do
        [ -z "$(owned "$owner")" ] || return 1
    done
    # This tag is generated by this run, never supplied by the caller.
    docker image rm "${project}-app" >"$work/down-image.log" 2>&1 || true
    remove_dirs || return 1
    rm -f "$record" "$work/app.env" "$fixture_env" "$work/absent.env"
}
cleanup() {
    status=$?
    trap - EXIT HUP INT TERM
    if [ "$started" = 1 ] && ! remove_resources; then
        echo "external-db-verify: cleanup failed; private diagnostics: $work" >&2
        status=1
    fi
    [ "$held" = 0 ] || rm -rf "$lock"
    exit "$status"
}
trap cleanup EXIT
trap 'exit 130' HUP INT TERM

[ ! -L "$root/.workspace" ] && [ ! -L "$work" ] || fail 'scratch root is a symbolic link'
mkdir -p "$work"
if ! mkdir "$lock" 2>/dev/null; then
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -z "$pid" ] || kill -0 "$pid" 2>/dev/null; then fail "a run already holds $lock"; fi
    mkdir "$work/reclaim" 2>/dev/null || fail 'another run is reclaiming the lock'
    pid=$(cat "$lock/pid" 2>/dev/null || true)
    if [ -z "$pid" ] || kill -0 "$pid" 2>/dev/null; then rmdir "$work/reclaim"; fail 'the previous run is still active'; fi
    rm -rf "$lock"
    mkdir "$lock" || { rmdir "$work/reclaim"; fail 'another run acquired the lock'; }
    rmdir "$work/reclaim"
fi
held=1
echo $$ >"$lock/pid"
for tool in docker openssl curl; do command -v "$tool" >/dev/null 2>&1 || fail "$tool is required"; done
docker info >/dev/null 2>&1 || fail 'cannot reach Docker'
docker compose version >"$work/versions.log" 2>&1 || fail 'Compose 2.20 or newer is required'
docker version >>"$work/versions.log" 2>&1
pin=$(sed -n 's/^POSTGRES_IMAGE=//p' "$root/server/postgres-image.env")
[ -n "$pin" ] || fail 'PostgreSQL image pin is missing'

# Before overwriting configuration or deleting anything, establish ownership.
for owner in "$fixture" "$project"; do
    if [ -n "$(owned "$owner")" ] && ! recorded; then fail "project $owner has resources not recorded by this checkout; nothing removed"; fi
done
if [ -e "$tls" ]; then
    recorded || fail 'scratch data has no matching ownership record; nothing removed'
fi
write_settings() {
password=$(openssl rand -hex 32)
admin_password=$(openssl rand -hex 32)
printf 'DATABASE_URL=postgres://sidereal:%s@external-db:5432/named?sslrootcert=/etc/sidereal/postgres/ca.crt\nSIDEREAL_PORT=%s\nSIDEREAL_DATABASE_TLS_PATH=%s\n' "$password" "$port" "$tls" >"$envfile"
printf 'POSTGRES_PASSWORD=%s\n' "$admin_password" >"$fixture_env"
cat >"$work/app.yml" <<EOF
services:
  app:
    networks:
      - fixture
networks:
  fixture:
    external: true
    name: $network
EOF
cat >"$work/fixture.yml" <<EOF
services:
  db:
    image: $pin
    environment:
      POSTGRES_PASSWORD: \${POSTGRES_PASSWORD:?fixture password required}
    command: [postgres, -c, ssl=on, -c, ssl_cert_file=/fixture/server.crt, -c, ssl_key_file=/fixture/server.key, -c, hba_file=/fixture/pg_hba.conf]
    volumes:
      - database:/var/lib/postgresql
      - type: bind
        source: $tls
        target: /fixture
        read_only: true
        bind:
          create_host_path: false
    networks:
      default:
        aliases: [external-db]
volumes:
  database:
EOF
}

# A killed run may have left incomplete settings. Reconstruct every file that
# Compose needs before removing recorded resources; down needs no old password.
write_settings
if recorded; then
    remove_resources || fail 'could not clean the previous recorded run'
    write_settings
fi
printf '%s\n' "$fixture $project" >"$record"

# One verified TLS start and one recreation exercise the deployment boundary.
started=1
mkdir -p "$tls"
chmod 755 "$tls"
say 'generating disposable fixture certificates'
openssl req -x509 -newkey rsa:2048 -nodes -keyout "$tls/ca.key" -out "$tls/ca.crt" -days 2 -subj '/CN=Sidereal external fixture CA' >"$work/certificates.log" 2>&1
openssl req -newkey rsa:2048 -nodes -keyout "$tls/server.key" -out "$tls/server.csr" -subj '/CN=external-db' >>"$work/certificates.log" 2>&1
printf 'subjectAltName=DNS:external-db\nextendedKeyUsage=serverAuth\n' >"$tls/server.ext"
openssl x509 -req -in "$tls/server.csr" -CA "$tls/ca.crt" -CAkey "$tls/ca.key" -set_serial 1 -out "$tls/server.crt" -days 2 -extfile "$tls/server.ext" >>"$work/certificates.log" 2>&1
rm -f "$tls/ca.key" "$tls/server.csr" "$tls/server.ext"
printf 'local all all trust\nhostnossl all all all reject\nhostssl all all all scram-sha-256\n' >"$tls/pg_hba.conf"
chmod 644 "$tls"/*.crt "$tls/pg_hba.conf"
chmod 600 "$tls/server.key"
helper "$tls" chown postgres:postgres /target/server.key >"$work/permissions.log" 2>&1
sql() { fixture_compose exec -T db psql -X -U postgres -d "${database:-postgres}" -v ON_ERROR_STOP=1 -Atc "$1"; }
fixture_identity() { docker inspect --format '{{.Id}} {{.State.StartedAt}}' "$(fixture_compose ps -q db)"; }
wait_database() {
    waited=0
    until fixture_compose exec -T db pg_isready -q -h 127.0.0.1; do
        [ "$waited" -lt 180 ] || fail 'fixture did not accept connections within 180 seconds'
        sleep 1
        waited=$((waited + 1))
    done
}
start_app() {
    compose up -d --no-build >"$work/app-up.log" 2>&1 || fail "app creation failed; see $work/app-up.log"
    deadline=$(($(date +%s) + 180))
    until curl -fsS --max-time 3 "http://127.0.0.1:$port/readyz" >"$work/http-body" 2>/dev/null; do
        [ "$(date +%s)" -lt "$deadline" ] || fail "app did not reach readiness; private diagnostics: $work"
        sleep 1
    done
    [ "$(cat "$work/http-body")" = '{"status":"ready"}' ] || fail 'unexpected readiness body'
}
retained() {
    sql "SELECT coalesce(jsonb_agg(to_jsonb(m) ORDER BY version), '[]') FROM _sqlx_migrations m"
    sql 'SELECT row_to_json(m) FROM sidereal_metadata m'
    compose exec -T app cat "$storage/$marker" "$storage/sentinel"
}
say 'building the packaged app image'
compose build >"$work/build.log" 2>&1 || fail "app build failed; see $work/build.log"
say 'starting the separate TLS-only PostgreSQL fixture'
fixture_compose up -d >"$work/fixture-up.log" 2>&1 || fail "fixture startup failed; see $work/fixture-up.log"
wait_database >"$work/fixture-ready.log" 2>&1
sql "CREATE ROLE sidereal LOGIN NOSUPERUSER NOCREATEDB PASSWORD '$password'" >"$work/provision.log" 2>&1
sql 'CREATE DATABASE named OWNER sidereal' >>"$work/provision.log" 2>&1
database=named
fixture_before=$(fixture_identity)
# Config can assert create_host_path:false; only Docker can enforce it.
say 'checking that a missing certificate directory is refused'
main_envfile=$envfile
sed "s|^SIDEREAL_DATABASE_TLS_PATH=.*|SIDEREAL_DATABASE_TLS_PATH=$work/absent-certificates|" "$envfile" >"$work/absent.env"
envfile="$work/absent.env"
if compose up -d --no-build >"$work/absent-certificates.log" 2>&1; then fail 'Compose accepted a missing certificate directory'; fi
grep -Fq 'bind source path does not exist' "$work/absent-certificates.log" || fail 'unexpected certificate source refusal'
[ ! -e "$work/absent-certificates" ] || fail 'Compose created the missing certificate directory'
[ -z "$(compose ps -a -q app)" ] || fail 'Compose created an app container without its certificate directory'
envfile=$main_envfile
rm -f "$work/absent.env"
start_app
[ "$(docker inspect --format '{{range .Mounts}}{{if eq .Destination "/etc/sidereal/postgres"}}{{.Source}} {{.RW}}{{end}}{{end}}' "$(compose ps -q app)")" = "$tls false" ] || fail 'certificate mount is not the generated read-only directory'
[ "$(sql 'SELECT count(*) FROM _sqlx_migrations WHERE success')" -gt 0 ] || fail 'no successful migrations'
compose exec -T app sh -c 'printf "retained external sentinel\n" > "$STORAGE_ROOT/sentinel"'
retained >"$work/retained-before"
say 'recreating the app while retaining the external database and storage'
compose down --timeout 10 >"$work/recreate.log" 2>&1
[ "$(fixture_identity)" = "$fixture_before" ] || fail 'app removal changed the external database'
docker network inspect "$network" >/dev/null || fail 'app removal deleted the external network'
start_app
retained >"$work/retained-after"
cmp "$work/retained-before" "$work/retained-after" || fail 'app recreation changed retained state'
[ "$(fixture_identity)" = "$fixture_before" ] || fail 'app recreation restarted the external database'
say 'TLS startup, external network ownership, and recreation passed'
