// Generates web/src/styles/tokens.css from DESIGN.md's front matter.
//
//   pnpm tokens          write the file
//   pnpm tokens:check    compare the file with DESIGN.md and write nothing
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { isMap, readDesignMd } from "./design-md.ts";

export const tokensCssPath = fileURLToPath(
  new URL("../src/styles/tokens.css", import.meta.url),
);

export function main(args: string[]): number {
  let css: string;
  try {
    css = buildTokensCss(readDesignMd().frontMatter);
  } catch (error) {
    if (!(error instanceof TokenError)) throw error;
    console.error(error.message);
    return 1;
  }

  if (!args.includes("--check")) {
    mkdirSync(dirname(tokensCssPath), { recursive: true });
    writeFileSync(tokensCssPath, css);
    return 0;
  }

  // Compare without carriage returns, so a checkout with CRLF line endings
  // does not count as drift.
  if (readIfExists(tokensCssPath)?.replaceAll("\r\n", "\n") === css) return 0;
  console.error(
    "web/src/styles/tokens.css does not match DESIGN.md. Run `pnpm tokens` in web/ to regenerate it.",
  );
  return 1;
}

// Returns the text of tokens.css: one custom property per primitive token,
// in DESIGN.md's order, grouped by where each token sits in the front matter,
// then one per semantic token, written as var() of the primitive it names.
// Throws a TokenError that names every token it cannot write safely.
export function buildTokensCss(frontMatter: Record<string, unknown>): string {
  checkTokens(frontMatter);

  const prefix = String(extensionOf(frontMatter)["css-prefix"]);
  const lines = [
    "/* Generated from DESIGN.md by `pnpm tokens`. Do not edit this file:",
    "   change DESIGN.md, then run `pnpm tokens` in web/. */",
    ":root {",
  ];

  for (const group of primitiveGroups(frontMatter)) {
    if (lines.length > 3) lines.push("");
    lines.push(`  /* ${group.path} */`);
    for (const [key, value] of Object.entries(group.tokens)) {
      lines.push(`  --${prefix}-${key}: ${String(value)};`);
    }
  }

  // A semantic value is never written as it stands: only the key of the
  // primitive it names is, and checkTokens() has made sure that key exists.
  const semantic = semanticTokens(frontMatter);
  if (Object.keys(semantic).length > 0) {
    if (lines.length > 3) lines.push("");
    lines.push("  /* x-sidereal.semantic */");
    for (const [key, value] of Object.entries(semantic)) {
      const target = parseReference(value)?.key;
      lines.push(`  --${prefix}-${key}: var(--${prefix}-${String(target)});`);
    }
  }

  lines.push("}", "");
  return lines.join("\n");
}

// Throws a TokenError that names every token the generators cannot write
// safely. Returns nothing when every token can be written.
export function checkTokens(frontMatter: Record<string, unknown>): void {
  const problems = findProblems(frontMatter);
  if (problems.length > 0) {
    throw new TokenError(
      [
        "DESIGN.md holds tokens that the token generators cannot write:",
        ...problems.map((problem) => `  - ${problem}`),
      ].join("\n"),
    );
  }
}

export interface TokenGroup {
  // Where the group sits in the front matter, such as `colors` or
  // `x-sidereal.font-size`.
  path: string;
  tokens: Record<string, unknown>;
}

export class TokenError extends Error {}

// Lists every reason the generator cannot write DESIGN.md's tokens. An empty
// list means every token can be written.
function findProblems(frontMatter: Record<string, unknown>): string[] {
  const problems: string[] = [];
  const extension = extensionOf(frontMatter);

  const prefix = extension["css-prefix"];
  if (typeof prefix !== "string" || !/^[a-z]+$/.test(prefix)) {
    problems.push(
      "x-sidereal.css-prefix must hold lowercase letters only, such as `sr`",
    );
  }

  // Component tokens hold properties of references, which the generator
  // cannot write yet.
  if (isMap(frontMatter.components)) {
    for (const key of Object.keys(frontMatter.components)) {
      problems.push(
        `${key} (in components): the generator cannot write component tokens yet. Add support to web/scripts/tokens.ts in the same pull request.`,
      );
    }
  }

  // The specification's typography group holds whole text styles, which
  // tokens.css cannot hold as single properties yet.
  if (
    isMap(frontMatter.typography) &&
    Object.keys(frontMatter.typography).length > 0
  ) {
    problems.push(
      "typography holds text styles, which the generator cannot write yet. Add support to web/scripts/tokens.ts in the same pull request.",
    );
  }
  for (const path of specGroups) {
    const tokens = frontMatter[path];
    if (tokens !== undefined && !isMap(tokens)) {
      problems.push(`${path} must be a map of tokens`);
    }
  }

  for (const [name, tokens] of Object.entries(extension)) {
    if (extensionSettings.includes(name)) continue;
    const path = `x-sidereal.${name}`;
    if (!(path in valueForms)) {
      problems.push(
        `${path} has no known value form. Add one to valueForms in web/scripts/tokens.ts.`,
      );
    } else if (!isMap(tokens)) {
      problems.push(`${path} must be a map of tokens`);
    }
  }

  const firstGroupOf = new Map<string, string>();
  for (const group of primitiveGroups(frontMatter)) {
    const form = valueForms[group.path];
    for (const [key, value] of Object.entries(group.tokens)) {
      const where = `${JSON.stringify(key)} (in ${group.path})`;
      const firstGroup = firstGroupOf.get(key);
      if (firstGroup !== undefined) {
        problems.push(`${where} is also a key in ${firstGroup}`);
      }
      firstGroupOf.set(key, group.path);

      if (!/^[a-z0-9-]+$/.test(key)) {
        problems.push(
          `${where}: a key may hold only lowercase letters, digits, and hyphens`,
        );
      }
      if (refusedText.test(String(value))) {
        problems.push(
          `${where}: a value may not hold a line break, ;, {, }, <, \\, or url(, because it could end its CSS property`,
        );
      } else if (form && !form.fits(value)) {
        problems.push(`${where}: the value must be ${form.description}`);
      }
    }
  }

  if (extension.semantic !== undefined && !isMap(extension.semantic)) {
    problems.push("x-sidereal.semantic must be a map of tokens");
  }
  for (const [key, value] of Object.entries(semanticTokens(frontMatter))) {
    const where = `${JSON.stringify(key)} (in x-sidereal.semantic)`;
    const firstGroup = firstGroupOf.get(key);
    if (firstGroup !== undefined) {
      problems.push(`${where} is also a key in ${firstGroup}`);
    }
    firstGroupOf.set(key, "x-sidereal.semantic");
    if (!/^[a-z0-9-]+$/.test(key)) {
      problems.push(
        `${where}: a key may hold only lowercase letters, digits, and hyphens`,
      );
    }
    const reference = parseReference(value);
    if (!reference) {
      problems.push(
        `${where}: the value must be exactly {<group>.<key>}, such as {colors.violet-600}, with nothing before or after it`,
      );
    } else if (!primitiveExists(frontMatter, reference)) {
      problems.push(
        `${where}: ${String(value)} names no primitive token in DESIGN.md`,
      );
    }
  }

  return problems;
}

interface Reference {
  group: string;
  key: string;
}

// A semantic value names one primitive: exactly `{<group>.<key>}`.
function parseReference(value: unknown): Reference | undefined {
  if (typeof value !== "string") return undefined;
  const match = /^\{([a-z0-9-]+)\.([a-z0-9-]+)\}$/.exec(value);
  return match ? { group: match[1], key: match[2] } : undefined;
}

// A group is one of the specification's groups, such as `colors`, or a
// primitive group under x-sidereal, such as `font-size`.
function primitiveExists(
  frontMatter: Record<string, unknown>,
  { group, key }: Reference,
): boolean {
  const path = specGroups.includes(group) ? group : `x-sidereal.${group}`;
  const found = primitiveGroups(frontMatter).find((g) => g.path === path);
  return found !== undefined && Object.hasOwn(found.tokens, key);
}

// The semantic tokens under x-sidereal.semantic, in DESIGN.md's order.
export function semanticTokens(
  frontMatter: Record<string, unknown>,
): Record<string, unknown> {
  const semantic = extensionOf(frontMatter).semantic;
  return isMap(semantic) ? semantic : {};
}

// Text that could end a custom property or load a file from another site.
// Only primitive values are checked against it: a semantic value must be a
// reference, and only the key it names is written.
const refusedText = /[\n\r;{}<\\]|url\(/i;

interface ValueForm {
  // Read as "the value must be <description>".
  description: string;
  fits(value: unknown): boolean;
}

const hexColor: ValueForm = {
  description: "a hex color: # and 6 hex digits, such as #0B0A0F",
  fits: (value) => typeof value === "string" && /^#[0-9A-Fa-f]{6}$/.test(value),
};

const wholePixels: ValueForm = {
  description: "a whole number of pixels, such as 14px",
  fits: (value) => typeof value === "string" && /^\d+px$/.test(value),
};

const ems: ValueForm = {
  description:
    "a decimal number of em, which may be negative, such as -0.015em",
  fits: (value) =>
    typeof value === "string" && /^-?(\d+(\.\d+)?|\.\d+)em$/.test(value),
};

const fraction: ValueForm = {
  description: "a number from 0 to 1, such as 0.45",
  fits: (value) => typeof value === "number" && value >= 0 && value <= 1,
};

const fontWeight: ValueForm = {
  description: "a whole number from 1 to 1000, such as 600",
  fits: (value) =>
    typeof value === "number" &&
    Number.isInteger(value) &&
    value >= 1 &&
    value <= 1000,
};

// Each item is a name in double quotes, or words that each start with a
// letter or a hyphen: `Inter, -apple-system, "Segoe UI", sans-serif`.
// A CSS-wide keyword, such as `inherit`, would make the custom property
// itself inherit or reset, not hold a font list.
const cssWideKeywords = [
  "inherit",
  "initial",
  "unset",
  "revert",
  "revert-layer",
  "default",
];

const fontFamily: ValueForm = {
  description:
    'a comma-separated font list, where each item is a name in double quotes or plain words other than a CSS-wide keyword such as inherit, for example Inter, "Segoe UI", sans-serif',
  fits: (value) =>
    typeof value === "string" &&
    value.split(",").every((item) => {
      const name = item.trim();
      return (
        /^("[^"]+"|[A-Za-z-][\w-]*( [A-Za-z-][\w-]*)*)$/.test(name) &&
        !cssWideKeywords.includes(name.toLowerCase())
      );
    }),
};

// The form each primitive group's values must take. An x-sidereal group that
// is missing here is refused, so a new group must add its form first.
const valueForms: Record<string, ValueForm | undefined> = {
  colors: hexColor,
  rounded: wholePixels,
  spacing: wholePixels,
  "x-sidereal.font-family": fontFamily,
  "x-sidereal.font-weight": fontWeight,
  "x-sidereal.font-size": wholePixels,
  "x-sidereal.line-height": wholePixels,
  "x-sidereal.letter-spacing": ems,
  "x-sidereal.opacity": fraction,
  "x-sidereal.blur": wholePixels,
  "x-sidereal.border-width": wholePixels,
  "x-sidereal.size": wholePixels,
};

// The specification's own primitive groups.
const specGroups = ["colors", "rounded", "spacing"];

// Keys under x-sidereal that hold settings, not primitive tokens.
const extensionSettings = ["css-prefix", "semantic"];

export function primitiveGroups(
  frontMatter: Record<string, unknown>,
): TokenGroup[] {
  const groups: TokenGroup[] = [];
  for (const path of specGroups) {
    const tokens = frontMatter[path];
    if (isMap(tokens)) groups.push({ path, tokens });
  }
  for (const [name, tokens] of Object.entries(extensionOf(frontMatter))) {
    if (extensionSettings.includes(name) || !isMap(tokens)) continue;
    groups.push({ path: `x-sidereal.${name}`, tokens });
  }
  return groups;
}

function extensionOf(
  frontMatter: Record<string, unknown>,
): Record<string, unknown> {
  const extension = frontMatter["x-sidereal"];
  return isMap(extension) ? extension : {};
}

function readIfExists(path: string): string | undefined {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return undefined;
  }
}

// Runs main() when Node runs this file directly, as `node scripts/<file>.ts`.
// It compares paths instead of using import.meta.main, which older Node
// releases lack: there, the check would silently do nothing.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  process.exitCode = main(process.argv.slice(2));
}
